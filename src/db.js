// ---- Drivers ------------------------------------------------------------------------

const toPg = (sql) => { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); };

function normalize(rows) {
  for (const r of rows) for (const k in r) {
    if (r[k] instanceof Date) r[k] = r[k].toISOString();
    else if (r[k] instanceof Uint8Array && !Buffer.isBuffer(r[k])) r[k] = Buffer.from(r[k]);
  }
  return rows;
}

async function pgDriver(url) {
  const pg = (await import('pg')).default;
  pg.types.setTypeParser(20, Number);     // bigint → number (counts, ms timestamps)
  pg.types.setTypeParser(1700, Number);   // numeric → number (sums)
  const pool = new pg.Pool({
    connectionString: url,
    max: Number(process.env.DATABASE_POOL_MAX || 5),
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
    ssl: /sslmode=disable|localhost|127\.0\.0\.1/.test(url) ? undefined : { rejectUnauthorized: true },
  });
  const wrap = (c) => ({
    async query(sql, params) { const r = await c.query(sql, params); return { rows: normalize(r.rows), rowCount: r.rowCount }; },
    exec: (sql) => c.query(sql),
  });
  return {
    name: 'postgres',
    ...wrap(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(wrap(client));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally { client.release(); }
    },
    end: () => pool.end(),
  };
}

async function pgliteDriver(dataDir) {
  const { PGlite } = await import('@electric-sql/pglite');
  const db = new PGlite(dataDir, { parsers: { 20: Number, 1700: Number } });
  await db.waitReady;
  const wrap = (c) => ({
    async query(sql, params) { const r = await c.query(sql, params); return { rows: normalize(r.rows), rowCount: r.affectedRows ?? r.rows.length }; },
    exec: (sql) => c.exec(sql),
  });
  return { name: 'pglite', ...wrap(db), transaction: (fn) => db.transaction((t) => fn(wrap(t))), end: () => db.close() };
}

// ---- Public API ---------------------------------------------------------------------

const txStore = new AsyncLocalStorage();
let ready = null;
let driver = null;

/** Connect and migrate once per process (safe to call on every request). */
export function init() {
  ready ||= (async () => {
    driver = config.databaseUrl
      ? await pgDriver(config.databaseUrl)
      : await pgliteDriver(config.pgliteDir === 'memory' ? undefined : path.resolve(config.pgliteDir));
    await migrate();
    return driver;
  })().catch((err) => { ready = null; throw err; });
  return ready;
}

export const driverName = () => driver?.name;

export async function query(sql, params = []) {
  await init();
  const conn = txStore.getStore() || driver;
  return conn.query(toPg(sql), params.map(p => (p === undefined ? null : typeof p === 'boolean' ? (p ? 1 : 0) : p)));
}

export const one = async (sql, ...p) => (await query(sql, p)).rows[0];
export const all = async (sql, ...p) => (await query(sql, p)).rows;
export const run = async (sql, ...p) => ({ changes: (await query(sql, p)).rowCount });
/** INSERT … and return the new row's id. */
export const insert = async (sql, ...p) => (await query(`${sql} RETURNING id`, p)).rows[0].id;

/** Run fn in a transaction; nested calls join the outer transaction. */
export async function tx(fn) {
  await init();
  if (txStore.getStore()) return fn();
  return driver.transaction((conn) => txStore.run(conn, fn));
}

export const isUniqueViolation = (err) => err?.code === '23505' || /duplicate key|unique constraint/i.test(err?.message || '');

export async function close() { if (driver) await driver.end(); ready = null; driver = null; }

async function migrate() {
  await driver.transaction(async (c) => {
    // Serialise concurrent cold starts.
    await c.query('SELECT pg_advisory_xact_lock(724501)');
    await c.query('CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)');
    const r = await c.query('SELECT version FROM schema_version');
    let version = r.rows[0]?.version ?? 0;
    if (!r.rows.length) await c.query('INSERT INTO schema_version (version) VALUES (0)');
    for (; version < SCHEMA.length; version++) {
      await c.exec(SCHEMA[version]);
      await c.query('UPDATE schema_version SET version = $1', [version + 1]);
    }
  });
}
