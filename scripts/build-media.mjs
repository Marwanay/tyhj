// Builds the responsive imagery from the approved Signature Chocolate Tray renders into
// public/media (served by the CDN) and writes src/views/media.js with their dimensions.
// Only the supplied renders are used; crops are framing choices, never alterations.
// Runs as the Vercel build step, and with `npm run setup` locally.
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeVariantsToDir } from '../src/lib/images.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = (f) => path.join(root, 'assets/source', f);
const outDir = path.join(root, 'public/media');
const STUDIO = src('signature-tray-studio.png');   // 1254 × 1254
const TABLE = src('signature-tray-table.png');     // 1536 × 1024
const ROUND = src('round-tray-studio.png');         // 1312 × 1199

const SITE = {
  'site-hero':          { file: STUDIO, alt: 'The Signature Chocolate Tray: gold-flecked chocolate domes in a clear tray beside cream gerberas' },
  'site-detail-gold':   { file: STUDIO, crop: { left: 640, top: 700, width: 520, height: 390 }, alt: 'Close-up of glossy chocolate domes finished with flecks of gold' },
  'site-detail-flowers':{ file: STUDIO, crop: { left: 40, top: 20, width: 560, height: 700 }, alt: 'Cream gerberas and folded leaves arranged at the head of the tray' },
  'site-table':         { file: TABLE, alt: 'The Signature Chocolate Tray set on a dining table with blush napkins and crystal glasses' },
  'site-table-setting': { file: TABLE, crop: { left: 960, top: 0, width: 576, height: 1024 }, alt: 'A place setting with blush linen beside the chocolate tray' },
  'site-table-tray':    { file: TABLE, crop: { left: 200, top: 250, width: 1150, height: 720 }, alt: 'The chocolate tray and flowers at the centre of a set table' },
};

// Gallery for the launch product (inserted into the database by the seed).
const PRODUCT = {
  'signature-tray-studio':  { file: STUDIO, alt: 'The Signature Chocolate Tray: rows of gold-flecked chocolate domes in a clear tray, with cream gerberas and folded leaves at one end' },
  'signature-tray-table':   { file: TABLE, alt: 'The Signature Chocolate Tray as a centrepiece on a dining table set with blush napkins and crystal glasses' },
  'signature-tray-detail':  { file: STUDIO, crop: { left: 600, top: 640, width: 600, height: 600 }, alt: 'Close-up of the glossy chocolate domes and their gold details' },
  'signature-tray-flowers': { file: STUDIO, crop: { left: 30, top: 20, width: 620, height: 760 }, alt: 'The cream gerbera arrangement at the head of the tray' },
};

// Gallery for the second product, the round tray (also inserted by the seed).
const ROUND_TRAY = {
  'round-tray-studio':  { file: ROUND, alt: 'The Signature Round Tray: gold-flecked chocolate domes in a round clear tray, around a vase of cream gerberas' },
  'round-tray-detail':  { file: ROUND, crop: { left: 160, top: 760, width: 620, height: 400 }, alt: 'Close-up of the gold-flecked chocolate domes in the round tray' },
  'round-tray-flowers': { file: ROUND, crop: { left: 290, top: 80, width: 640, height: 720 }, alt: 'Cream gerberas, small white flowers and folded leaves in the clear vase at the centre of the tray' },
};

async function build(defs) {
  const manifest = {};
  for (const [key, def] of Object.entries(defs)) {
    const out = await writeVariantsToDir(def.file, key, outDir, { crop: def.crop });
    manifest[key] = { ...out, alt: def.alt };
    console.log(key, `${out.width}×${out.height}`, out.widths.join(','));
  }
  return manifest;
}

const manifestFile = path.join(root, 'src/views/media.js');
const expected = [...Object.keys(SITE), ...Object.keys(PRODUCT), ...Object.keys(ROUND_TRAY)].map(k => path.join(outDir, `${k}-480.avif`));
if (process.argv.includes('--if-missing') && existsSync(manifestFile) && expected.every(existsSync)) {
  console.log('Media already built — skipping.');
} else {
  const site = await build(SITE);
  const product = await build(PRODUCT);
  const round = await build(ROUND_TRAY);
  await fs.writeFile(manifestFile, '// Generated by scripts/build-media.mjs — do not edit.\n' +
    `export const SITE_MEDIA = ${JSON.stringify(site, null, 2)};\n\nexport const PRODUCT_MEDIA = ${JSON.stringify(product, null, 2)};\n\n` +
    `export const ROUND_TRAY_MEDIA = ${JSON.stringify(round, null, 2)};\n`);
}
