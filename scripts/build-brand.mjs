// Compiles the traced brand SVGs into a JS module so the server never reads files at runtime.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (n) => fs.readFileSync(path.join(root, 'public/brand', `${n}.svg`), 'utf8').trim();
fs.writeFileSync(path.join(root, 'src/views/brand.js'),
  `// Generated by scripts/build-brand.mjs from public/brand/*.svg — do not edit.\n` +
  `export const WORDMARK = ${JSON.stringify(read('wordmark'))};\n` +
  `export const MONOGRAM = ${JSON.stringify(read('monogram'))};\n` +
  `export const STACKED = ${JSON.stringify(read('logo-stacked'))};\n`);
console.log('src/views/brand.js written');
